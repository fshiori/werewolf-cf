#!/usr/bin/env node

import { readdir, stat } from "node:fs/promises";
import { relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_REF_ROOT = "ref/diam1.3.61.kz_Build0912";
const ASSET_EXTENSIONS = new Set([".gif", ".jpg", ".jpeg", ".png", ".swf"]);

function extensionOf(path) {
  const match = path.toLowerCase().match(/\.[^.]+$/);
  return match?.[0] ?? "";
}

async function walk(dir, root = dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const absolute = resolve(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...await walk(absolute, root));
      continue;
    }
    if (!entry.isFile()) {
      continue;
    }
    const extension = extensionOf(entry.name);
    if (ASSET_EXTENSIONS.has(extension)) {
      const info = await stat(absolute);
      files.push({
        path: relative(root, absolute).split(sep).join("/"),
        bytes: info.size
      });
    }
  }
  return files;
}

function categoryFor(path) {
  const filename = path.split("/").at(-1) ?? path;
  if (path.startsWith("user_icon/")) {
    return "default user icons";
  }
  if (path.startsWith("user_emot/")) {
    return "emotes";
  }
  if (path.startsWith("swf/") || filename.endsWith(".swf")) {
    return "legacy sounds";
  }
  if (filename.startsWith("room_option_") || filename === "rei.gif" || filename === "conn_look.gif") {
    return "room option icons";
  }
  if (filename.startsWith("role_")) {
    return "role and result icons";
  }
  if (filename.startsWith("victory_role_")) {
    return "victory images";
  }
  if (filename.startsWith("max") || ["waiting.gif", "playing.gif", "endroom.gif"].includes(filename)) {
    return "room list status";
  }
  if (["grave.gif", "wolf.gif", "dummy_boy_user_icon.gif", "objection.gif"].includes(filename)) {
    return "gameplay markers";
  }
  if (filename.includes("_bg") || filename.includes("_title") || filename.startsWith("top_") || filename.startsWith("user_regist_") || filename === "triphelp.jpg") {
    return "page chrome";
  }
  return "other";
}

function summarize(files) {
  const categories = new Map();
  for (const file of files) {
    const category = categoryFor(file.path);
    const current = categories.get(category) ?? { count: 0, bytes: 0, files: [] };
    current.count += 1;
    current.bytes += file.bytes;
    current.files.push(file.path);
    categories.set(category, current);
  }
  return [...categories.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([category, value]) => ({
      category,
      count: value.count,
      bytes: value.bytes,
      files: value.files.sort()
    }));
}

function renderMarkdown(refRoot, categories) {
  const totalCount = categories.reduce((sum, category) => sum + category.count, 0);
  const totalBytes = categories.reduce((sum, category) => sum + category.bytes, 0);
  const rows = categories.map((category) => `| ${category.category} | ${category.count} | ${category.bytes} | ${category.files.slice(0, 8).map((file) => `\`${file}\``).join("<br>")}${category.files.length > 8 ? "<br>..." : ""} |`).join("\n");
  const details = categories.map((category) => [
    `### ${category.category}`,
    "",
    ...category.files.map((file) => `- \`${file}\``),
    ""
  ].join("\n")).join("\n");

  return `# Reference Asset Inventory

Reference root: \`${refRoot}\`

Generated by \`node scripts/inventory-reference-assets.mjs\`.

Total assets: ${totalCount}

Total bytes: ${totalBytes}

## Summary

| Category | Count | Bytes | Sample files |
| --- | ---: | ---: | --- |
${rows}

## Files

${details}`.trimEnd() + "\n";
}

export async function inventoryReferenceAssets(refRoot = DEFAULT_REF_ROOT) {
  const absoluteRoot = resolve(refRoot);
  const files = await walk(absoluteRoot, absoluteRoot);
  return summarize(files);
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : "";
if (invokedPath === fileURLToPath(import.meta.url)) {
  const refRoot = process.argv[2] ?? DEFAULT_REF_ROOT;
  const categories = await inventoryReferenceAssets(refRoot);
  process.stdout.write(renderMarkdown(refRoot, categories));
}
